#!/usr/bin/env python3
"""Validate or regenerate the standalone Python 3.12 dependency snapshots.

Check (stdlib only): python scripts/dependency-locks.py --check
Regenerate: install uv==0.9.7 in a NEW temporary tools environment, then run
python scripts/dependency-locks.py --generate --uv /tmp/tools/bin/uv
The resolver evaluates target markers, not the host markers used by pip's
--platform flag. Resolution is evidence of available wheels, not native testing.
See packaging/locks/README.md for installation and scope.
"""
from __future__ import annotations

import argparse
import hashlib
from importlib import metadata
import os
from pathlib import Path
import re
import platform
import subprocess
import tempfile
import sys

ROOT = Path(__file__).resolve().parents[1]
LOCKS = ROOT / "packaging" / "locks"
UV_VERSION = "0.9.7"
CUTOFF = "2026-11-06"
TARGETS = {
    "linux-x86_64-cpu": ("x86_64-manylinux_2_35", "cpu", "2.7.1+cpu", "0.22.1+cpu"),
    "windows-x86_64-cu128": ("x86_64-pc-windows-msvc", "cu128", "2.7.1+cu128", "0.22.1+cu128"),
    "macos-arm64": ("aarch64-apple-darwin", None, "2.7.1", "0.22.1"),
    "macos-x86_64": ("x86_64-apple-darwin", None, "2.2.2", "0.17.2"),
}
BASE = """numpy>=1.24
opencv-python-headless>=4.8
imageio-ffmpeg>=0.4.9
ultralytics==8.4.183
scikit-learn==1.9.1
matplotlib>=3.7
PySide6>=6.7,<7
PyInstaller>=6.16,<7
pyinstaller-hooks-contrib>=2025.8
setuptools>=77
build>=1.2
onnx>=1.16,<2
onnxruntime>=1.18,<2
"""


def inputs(target: str) -> str:
    _, backend, torch, vision = TARGETS[target]
    text = BASE + f"torch=={torch}\ntorchvision=={vision}\n"
    if backend:
        text += "openvino>=2024.0,<2027\n"
    if target == "macos-x86_64":
        text += "numpy==1.26.4\nopencv-python==4.11.0.86\nopencv-python-headless==4.11.0.86\n"
    return text


def header(target: str) -> str:
    spec = f"{UV_VERSION}\n{CUTOFF}\n{TARGETS[target]}\nmacos-deployment=15.0\n{inputs(target)}"
    digest = hashlib.sha256(spec.encode()).hexdigest()
    return (f"# Generated by scripts/dependency-locks.py; target={target}; Python=3.12\n"
            f"# uv={UV_VERSION}; exclude-newer={CUTOFF}; input-sha256={digest}\n"
            "# Full runtime + desktop + inference + installer/build dependencies.\n")


def pins(text: str) -> dict[str, str]:
    result = {}
    for entry in text.replace("\\\n", " ").splitlines():
        if not entry.strip() or entry.startswith("#") or entry.startswith("--"):
            continue
        match = re.fullmatch(r"([A-Za-z0-9_.-]+)==([A-Za-z0-9_.+!-]+)\s+((?:--hash=sha256:[a-f0-9]{64}\s*)+)", entry)
        if not match:
            raise ValueError(f"Unpinned, unhashed or invalid requirement: {entry[:100]}")
        name = re.sub(r"[-_.]+", "-", match[1]).lower()
        if name in result:
            raise ValueError(f"Duplicate requirement: {name}")
        result[name] = match[2]
    if not result:
        raise ValueError("Empty dependency lock")
    return result


def validate(target: str, text: str) -> None:
    if not text.startswith(header(target)):
        raise ValueError(f"{target}: lock input header has drifted; regenerate")
    dependencies = pins(text)
    for line in inputs(target).splitlines():
        if "==" in line:
            name, version = line.split("==")
            name = re.sub(r"[-_.]+", "-", name).lower()
            if dependencies.get(name) != version:
                raise ValueError(f"{target}: expected input {name}=={version}")
    for name, version in {"torch": TARGETS[target][2], "torchvision": TARGETS[target][3]}.items():
        if dependencies.get(name) != version:
            raise ValueError(f"{target}: expected {name}=={version}")
    if target == "macos-x86_64" and dependencies.get("numpy") != "1.26.4":
        raise ValueError("Intel macOS requires NumPy 1.26.4 for Torch 2.2.2")
    for name in ("pyside6", "pyinstaller", "pyinstaller-hooks-contrib", "setuptools", "build",
                 "onnx", "onnxruntime", "ultralytics", "imageio-ffmpeg", "scikit-learn", "matplotlib"):
        if name not in dependencies:
            raise ValueError(f"{target}: missing {name}")
    backend = TARGETS[target][1]
    options = [line for line in text.splitlines() if line.startswith("--")]
    expected_order = ["--index-url https://pypi.org/simple"]
    if backend:
        expected_order.append(f"--extra-index-url https://download.pytorch.org/whl/{backend}")
    if options != expected_order:
        raise ValueError(f"{target}: unexpected package index options: {options}")
    if ("openvino" in dependencies) != bool(backend):
        raise ValueError(f"{target}: OpenVINO must be Windows/Linux only")
    if target.startswith("macos") and any(name.startswith("nvidia-") and name != "nvidia-ml-py" for name in dependencies):
        raise ValueError(f"{target}: CUDA dependency leaked into macOS")
    if target.startswith("windows") and "pefile" not in dependencies:
        raise ValueError("Windows marker dependency pefile missing")
    if target.startswith("macos") and "macholib" not in dependencies:
        raise ValueError("macOS marker dependency macholib missing")


def generate(target: str, uv: str, directory: Path) -> str:
    source = directory / f"{target}.in"
    destination = directory / f"{target}.txt"
    source.write_text(inputs(target), encoding="utf-8")
    triple, backend, _, _ = TARGETS[target]
    command = [uv, "--no-config", "--quiet", "pip", "compile", str(source),
               "--python-version", "3.12", "--python-platform", triple,
               "--default-index", "https://pypi.org/simple", "--exclude-newer", CUTOFF,
               "--generate-hashes", "--no-header", "--no-annotate", "--emit-index-url",
               "--only-binary", ":all:", "--output-file", str(destination)]
    if backend:
        command += ["--torch-backend", backend]
    # Avoid user uv/pip configuration, environment overrides, or existing caches.
    environment = {k: v for k, v in os.environ.items()
                   if not k.startswith(("UV_", "PIP_"))}
    environment["UV_CACHE_DIR"] = str(directory / "cache")
    environment["MACOSX_DEPLOYMENT_TARGET"] = "15.0"
    subprocess.run(command, check=True, env=environment)
    text = destination.read_text(encoding="utf-8")
    # uv's torch-backend index is scoped internally and not emitted by compile.
    # pip needs this source to retrieve the exact local-version Torch pins.
    text = "\n".join(line for line in text.splitlines() if not line.startswith(("--index-url", "--extra-index-url")))
    options = "--index-url https://pypi.org/simple\n"
    if backend:
        options += f"--extra-index-url https://download.pytorch.org/whl/{backend}\n"
    text = header(target) + options + text + "\n"
    validate(target, text)
    return text


def check_installed(target):
    text = (LOCKS / f'{target}.txt').read_text(encoding='utf-8')
    validate(target, text)
    for name, version in pins(text).items():
        # Ultralytics declares the GUI OpenCV distribution. Candidate builds
        # deliberately replace it with the exactly pinned headless distribution.
        if name == 'opencv-python':
            continue
        if metadata.version(name) != version:
            raise ValueError(f'Installed {name} differs from {target} lock')
    result = pip_run(['check'], text=True, stdout=subprocess.PIPE, stderr=subprocess.PIPE)
    allowed = f'ultralytics {pins(text)["ultralytics"]} requires opencv-python, which is not installed.'
    if result.returncode and result.stdout.strip() != allowed:
        raise ValueError('Dependency check failed: ' + result.stdout + result.stderr)


def pip_run(arguments, **kwargs):
    environment = {key: value for key, value in os.environ.items()
                   if not key.startswith('PIP_') and key not in {'PYTHONPATH', 'PYTHONHOME'}}
    environment['PIP_CONFIG_FILE'] = os.devnull
    return subprocess.run([sys.executable, '-I', '-m', 'pip', '--isolated',
                           '--disable-pip-version-check', *arguments], env=environment, **kwargs)


def install_locked(target):
    if sys.version_info[:2] != (3, 12) or sys.prefix == sys.base_prefix:
        raise ValueError('Install snapshots only into a new Python 3.12 virtual environment')
    expected_system = ('Windows' if target.startswith('windows') else
                       'Darwin' if target.startswith('macos') else 'Linux')
    expected_arch = 'arm64' if target == 'macos-arm64' else 'x86_64'
    actual_arch = platform.machine().lower().replace('amd64', 'x86_64')
    if (platform.system(), actual_arch) != (expected_system, expected_arch):
        raise ValueError('Dependency target does not match this machine')
    config = Path(sys.prefix) / 'pyvenv.cfg'
    if not config.is_file() or re.search(r'include-system-site-packages\s*=\s*true',
                                        config.read_text().lower()):
        raise ValueError('Build environment must be an isolated new virtual environment')
    installed = {re.sub(r'[-_.]+', '-', dist.metadata['Name']).lower()
                 for dist in metadata.distributions() if dist.metadata['Name']}
    if installed - {'pip', 'setuptools', 'wheel'}:
        raise ValueError('Build environment is populated; create a new virtual environment')
    path = LOCKS / f'{target}.txt'
    text = path.read_text(encoding='utf-8')
    validate(target, text)
    pip_run(['install', '--no-user', '--prefix', sys.prefix, '--require-hashes',
             '--only-binary=:all:', '-r', str(path)], check=True)
    pip_run(['check'], check=True)
    entry = next(line for line in text.replace('\\\n', ' ').splitlines()
                 if line.startswith('opencv-python-headless=='))
    with tempfile.TemporaryDirectory(prefix='scout-headless-lock-') as directory:
        requirement = Path(directory) / 'headless.txt'
        requirement.write_text('--index-url https://pypi.org/simple\n' + entry + '\n')
        pip_run(['uninstall', '-y', 'opencv-python', 'opencv-python-headless'], check=True)
        pip_run(['install', '--no-user', '--prefix', sys.prefix, '--no-deps', '--require-hashes',
                 '--only-binary=:all:', '-r', str(requirement)], check=True)
    pip_run(['install', '--no-user', '--prefix', sys.prefix, '--no-deps', '--no-build-isolation',
             str(ROOT) + '[desktop,inference]'], check=True)
    check_installed(target)


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    mode = parser.add_mutually_exclusive_group(required=True)
    mode.add_argument("--check", action="store_true")
    mode.add_argument('--install', action='store_true', help='Install into a new native Python3.12 venv')
    mode.add_argument('--check-installed', action='store_true')
    mode.add_argument("--generate", action="store_true")
    mode.add_argument("--verify-resolution", action="store_true", help="Resolve again and compare; network required")
    parser.add_argument("--uv", default="uv")
    parser.add_argument("--target", choices=TARGETS)
    args = parser.parse_args()
    if args.install or args.check_installed:
        if not args.target:
            parser.error('--target is required for installation checks')
        (install_locked if args.install else check_installed)(args.target)
        return
    targets = [args.target] if args.target else list(TARGETS)
    if not args.check:
        version = subprocess.check_output([args.uv, "--version"], text=True).strip()
        if version != f"uv {UV_VERSION}":
            parser.error(f"Expected uv {UV_VERSION}, got {version}")
    with tempfile.TemporaryDirectory(prefix="scout-dependency-locks-") as work:
        for target in targets:
            path = LOCKS / f"{target}.txt"
            if args.check:
                validate(target, path.read_text(encoding="utf-8"))
            else:
                text = generate(target, args.uv, Path(work))
                if args.generate:
                    LOCKS.mkdir(parents=True, exist_ok=True)
                    path.write_text(text, encoding="utf-8")
                elif path.read_text(encoding="utf-8") != text:
                    raise SystemExit(f"{target}: resolution differs from committed lock")
            print(f"{target}: {'generated' if args.generate else 'checked'}")


if __name__ == "__main__":
    main()
